#ifndef FRAMEWORK_GLOBAL_H
#define FRAMEWORK_GLOBAL_H

/*
  Marks the API the framework and the degradations expose, on 58 headers.

  B: it expands to nothing, and that is correct: ADD_LIBRARY() builds every
  library of this project as STATIC, and there is no BUILD_SHARED_LIBS
  option, so there is nothing to export from and nothing to import. The
  CMAKE_CXX_VISIBILITY_PRESET of the root CMakeLists.txt hides the symbols
  of the one shared object that is built, the python module, which marks
  its own entry points; the static libraries are unaffected.

  What it is for is the day a library here becomes SHARED. That day this
  macro is not enough, and the thing to do is not to fill it in by hand:

    - the macro is used by two targets, DocCreatorFramework and
      DocCreatorDegradations, and an export macro belongs to one library.
      Each needs its own, generated by CMake's GenerateExportHeader module
      (generate_export_header(<target>)), and the 58 headers have to be
      split between the two;
    - a header of a static library must see <TARGET>_STATIC_DEFINE, or the
      macro expands to an import attribute and the link fails.

  Until then this is the honest state: a name that says which declarations
  are the API, and expands to nothing because nothing is exported.
*/
#define FRAMEWORK_EXPORT

#endif // FRAMEWORK_GLOBAL_H
